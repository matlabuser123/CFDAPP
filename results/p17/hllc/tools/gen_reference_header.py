#!/usr/bin/env python3
"""Emit a C++ header of reference values by IMPORTING the frozen exact_riemann.py.

The reference script is FROZEN (its sha256 is recorded in logs/02_freeze.log). This generator does
not modify it -- it imports it -- so the freeze stays intact. P17.6 taught that lesson the hard way:
a frozen document was edited 174 s after freezing because the edit was bundled into other work.

Transcribing 60-digit values into C++ by hand is the other risk this removes: every number in the
generated header comes straight from the frozen script's own output.

usage: python3 gen_reference_header.py > ../../../tests/unit/compressible/hllc_reference_data.hpp
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import exact_riemann as ref  # noqa: E402  (path must be set first)

from mpmath import mp, fabs, mpf  # noqa: E402


def d(x):
    """A double literal with enough digits to round-trip exactly."""
    return mp.nstr(x, 20, strip_zeros=False)


def ident(name):
    return name.replace("-", "_")


def main():
    cases = ref.build_cases()
    print("#pragma once")
    print("")
    print("// GENERATED by results/p17/hllc/tools/gen_reference_header.py, which imports the FROZEN")
    print("// results/p17/hllc/tools/exact_riemann.py (mpmath, 60 decimal digits, no CFDApp code).")
    print("// DO NOT EDIT BY HAND. Every value here is the independent reference required by the")
    print("// frozen G6(f) criterion; adopting CFDApp output as a reference is forbidden.")
    print("//")
    print("// gamma = %s   R = %s   cp = %s" % (d(ref.GAMMA), d(ref.R_GAS), d(ref.CP)))
    print("")
    print('#include "cfd/core/Types.hpp"')
    print("")
    print("namespace cfd_test::hllc_ref {")
    print("")
    print("using cfd::Real;")
    print("")
    print("inline constexpr Real kGamma = %s;" % d(ref.GAMMA))
    print("inline constexpr Real kGasConstant = %s;" % d(ref.R_GAS))
    print("inline constexpr Real kSpecificHeatPressure = %s;" % d(ref.CP))
    print("")
    print("struct Side {")
    print("  Real density;")
    print("  Real u, v, w;")
    print("  Real pressure;")
    print("  Real temperature;")
    print("  Real speedOfSound;")
    print("  Real totalEnergyDensity;")
    print("};")
    print("")
    print("struct Case {")
    print("  const char* name;")
    print("  Side left;")
    print("  Side right;")
    print("  Real nx, ny, nz;")
    print("  Real sL, sStar, sR;")
    print("  Real denominator, denominatorBound, denominatorRatio;")
    print("  Real starDensityLeft, starDensityRight;")
    print("  const char* branch;")
    print("  Real flux[5];        // the 60-digit HLLC flux -- IMPLEMENTATION reference")
    print("  bool hasExact;       // is a 1D exact solution meaningful for this case?")
    print("  bool hllcIsExact;    // is HLLC ALGEBRAICALLY exact here? (gate criterion X1)")
    print("  Real exactFlux[5];   // the exact Godunov flux -- PHYSICAL reference")
    print("  Real exactLeftmostWave, exactRightmostWave;")
    print("  Real fluxScale[5];   // the non-collapsing normalisation scale")
    print("  Real hllFlux[5];     // contact wave DELETED -- the V2 control's reference")
    print("};")
    print("")

    # The cases where HLLC is algebraically exact, established by the frozen reference run.
    exact_names = {
        "uniform_x", "uniform_oblique", "stationary_contact", "moving_contact",
        "supersonic_right", "supersonic_left", "near_sonic_left", "strong_density_ratio",
    }

    rows = []
    for name, (rho_l, vel_l, p_l), (rho_r, vel_r, p_r), n in cases:
        h = ref.hllc(rho_l, vel_l, p_l, rho_r, vel_r, p_r, n)
        a_l = ref.sound_speed(rho_l, p_l)
        a_r = ref.sound_speed(rho_r, p_r)
        # T from p = rho R T, so the C++ side can build the state through P17.2/P17.5.
        t_l = p_l / (rho_l * ref.R_GAS)
        t_r = p_r / (rho_r * ref.R_GAS)
        sc = ref.flux_scales(rho_l, p_l, a_l, rho_r, p_r, a_r)

        ut_l = [vel_l[i] - h["unL"] * n[i] for i in range(3)]
        ut_r = [vel_r[i] - h["unR"] * n[i] for i in range(3)]
        has_exact = all(fabs(ut_l[i] - ut_r[i]) < mpf("1e-50") for i in range(3))
        if has_exact:
            rho0, un0, p00 = ref.exact_sample_at_zero(rho_l, h["unL"], p_l, rho_r, h["unR"], p_r)
            vel0 = [ut_l[i] + un0 * n[i] for i in range(3)]
            fx = ref.euler_flux(rho0, vel0, p00, n)
            wl, wr = ref.exact_wave_extremes(rho_l, h["unL"], p_l, rho_r, h["unR"], p_r)
        else:
            fx = [mpf(0)] * 5
            wl = wr = mpf(0)

        side_l = "{%s, %s, %s, %s, %s, %s, %s, %s}" % (
            d(rho_l), d(vel_l[0]), d(vel_l[1]), d(vel_l[2]), d(p_l), d(t_l), d(a_l),
            d(ref.total_energy_density(rho_l, vel_l, p_l)))
        side_r = "{%s, %s, %s, %s, %s, %s, %s, %s}" % (
            d(rho_r), d(vel_r[0]), d(vel_r[1]), d(vel_r[2]), d(p_r), d(t_r), d(a_r),
            d(ref.total_energy_density(rho_r, vel_r, p_r)))

        rows.append(
            '    {"%s",\n     %s,\n     %s,\n     %s, %s, %s,\n'
            '     %s, %s, %s,\n     %s, %s, %s,\n     %s, %s,\n     "%s",\n'
            '     {%s},\n     %s, %s,\n     {%s},\n     %s, %s,\n     {%s},\n     {%s}}'
            % (name, side_l, side_r, d(n[0]), d(n[1]), d(n[2]),
               d(h["sL"]), d(h["sStar"]), d(h["sR"]),
               d(h["denom"]), d(h["denomBound"]), d(h["denomRatio"]),
               d(h["rhoStarL"]), d(h["rhoStarR"]), h["branch"],
               ", ".join(d(c) for c in h["flux"]),
               "true" if has_exact else "false",
               "true" if (has_exact and name in exact_names) else "false",
               ", ".join(d(c) for c in fx),
               d(wl), d(wr),
               ", ".join(d(c) for c in sc),
               ", ".join(d(c) for c in h["fluxHLL"])))

    print("inline constexpr Case kCases[] = {")
    print(",\n".join(rows))
    print("};")
    print("")
    print("inline constexpr int kCaseCount = %d;" % len(rows))
    print("")
    print("// Davis (Toro 10.48) wave speeds for the SAME cases. Control V1's reference: this")
    print("// estimator fails to bound the true signal speeds in 8 of 14 cases.")
    print("struct DavisSpeeds { const char* name; Real sL, sR; bool boundsSignal; };")
    print("inline constexpr DavisSpeeds kDavis[] = {")
    drows = []
    for name, (rho_l, vel_l, p_l), (rho_r, vel_r, p_r), n in cases:
        hd = ref.hllc(rho_l, vel_l, p_l, rho_r, vel_r, p_r, n, "davis")
        ut_l = [vel_l[i] - hd["unL"] * n[i] for i in range(3)]
        ut_r = [vel_r[i] - hd["unR"] * n[i] for i in range(3)]
        ok = True
        if all(fabs(ut_l[i] - ut_r[i]) < mpf("1e-50") for i in range(3)):
            wl, wr = ref.exact_wave_extremes(rho_l, hd["unL"], p_l, rho_r, hd["unR"], p_r)
            ok = bool(hd["sL"] <= wl and hd["sR"] >= wr)
        drows.append('    {"%s", %s, %s, %s}'
                     % (name, d(hd["sL"]), d(hd["sR"]), "true" if ok else "false"))
    print(",\n".join(drows))
    print("};")
    print("")
    print("}  // namespace cfd_test::hllc_ref")


if __name__ == "__main__":
    main()
