"""P17.9 -- generate the C++ reference header from the FROZEN reference.

This file IMPORTS results/p17/shock_validation/tools/riemann_reference.py rather than editing it,
which is why that file's sha256 in logs/02_freeze.log still matches after the header is produced.
Same pattern as P17.7's gen_reference_header.py.

WHAT IS EMBEDDED, AND WHAT IS NOT -- the split matters.

  EMBEDDED as data: the STAR STATE and the WAVE SPEEDS. Those come from a nonlinear Newton solve on
  the pressure function, which is the part of an exact Riemann solution that can be subtly wrong,
  and it stays in Python at 60 digits where it is cross-checked against P17.7's independent
  derivation and against eight defining physical properties.

  COMPUTED in C++: the profile at a given x/t, from the embedded star state, using the algebraic
  self-similar formulas. That is sampling, not solving. Re-deriving it in C++ costs ~30 lines and
  avoids a 150 kB header of 1400 tabulated rows.

  EMBEDDED as a CROSS-CHECK: 41 spot points of the profile, computed in Python. The C++ sampler must
  reproduce every one to 1e-12. If the C++ sampling algebra is wrong, that test fails -- so the
  convenience of computing the profile in C++ does not cost the independence of the reference.
"""

import sys

sys.path.insert(0, "results/p17/shock_validation/tools")
from riemann_reference import (GAMMA, R_GAS, CP, SOD_LEFT, SOD_RIGHT, sample, wave_structure,
                               normal_shock, verify_defining_properties, verify_normal_shock)
from mpmath import mp, mpf, nstr

mp.dps = 60


def d(x):
    """A double literal with enough digits to round-trip."""
    return nstr(mpf(x), 17)


def main(path):
    # the reference REFUSES to emit unless its defining properties hold -- run them here too, so a
    # broken reference cannot silently produce a header
    verify_defining_properties(SOD_LEFT, SOD_RIGHT, "sod")
    verify_normal_shock("2.0")

    w = wave_structure(SOD_LEFT, SOD_RIGHT)
    ns = normal_shock("2.0")
    t_end = mpf("0.2")
    x0 = mpf("0.5")

    out = []
    a = out.append
    a("// GENERATED by results/p17/shock_validation/tools/gen_shock_reference.py")
    a("// from the FROZEN results/p17/shock_validation/tools/riemann_reference.py")
    a("// (sha256 recorded in results/p17/shock_validation/logs/02_freeze.log).")
    a("//")
    a("// DO NOT EDIT BY HAND. Every value is the exact Riemann / normal-shock solution at the")
    a("// PROJECT's gamma = cp/cv with R = 287.05, cp = 1005 -- NOT the textbook 1.4. Regenerate")
    a("// with:  python3 results/p17/shock_validation/tools/gen_shock_reference.py <this path>")
    a("//")
    a("// The generator refuses to run unless the reference satisfies its eight defining physical")
    a("// properties (Rankine-Hugoniot across the shock, the Riemann invariant and isentrope through")
    a("// the fan, wave ordering), so a header can never be produced from a broken solution.")
    a("#pragma once")
    a("")
    a("namespace cfd::shock_reference {")
    a("")
    a("inline constexpr double kGamma = %s;" % d(GAMMA))
    a("inline constexpr double kGasConstant = %s;" % d(R_GAS))
    a("inline constexpr double kCp = %s;" % d(CP))
    a("")
    a("// --- Sod shock tube, exactly as the frozen G7 criterion states it ---------------------")
    a("inline constexpr double kSodLeftDensity = %s;" % d(SOD_LEFT[0]))
    a("inline constexpr double kSodLeftVelocity = %s;" % d(SOD_LEFT[1]))
    a("inline constexpr double kSodLeftPressure = %s;" % d(SOD_LEFT[2]))
    a("inline constexpr double kSodRightDensity = %s;" % d(SOD_RIGHT[0]))
    a("inline constexpr double kSodRightVelocity = %s;" % d(SOD_RIGHT[1]))
    a("inline constexpr double kSodRightPressure = %s;" % d(SOD_RIGHT[2]))
    a("")
    a("// the star state, from the 60-digit Newton solve")
    a("inline constexpr double kSodPStar = %s;" % d(w["p_star"]))
    a("inline constexpr double kSodUStar = %s;" % d(w["u_star"]))
    a("inline constexpr double kSodRhoStarLeft = %s;" % d(w["rho_star_left"]))
    a("inline constexpr double kSodRhoStarRight = %s;" % d(w["rho_star_right"]))
    a("inline constexpr double kSodSoundSpeedLeft = %s;" % d(w["a_left"]))
    a("inline constexpr double kSodSoundSpeedStarLeft = %s;" % d(w["a_star_left"]))
    a("")
    a("// wave speeds, x/t")
    a("inline constexpr double kSodRarefactionHeadSpeed = %s;" % d(w["rarefaction_head_speed"]))
    a("inline constexpr double kSodRarefactionTailSpeed = %s;" % d(w["rarefaction_tail_speed"]))
    a("inline constexpr double kSodContactSpeed = %s;" % d(w["contact_speed"]))
    a("inline constexpr double kSodShockSpeed = %s;" % d(w["shock_speed"]))
    a("")
    a("// positions at the frozen end time t = 0.2 with x0 = 0.5")
    a("inline constexpr double kSodEndTime = %s;" % d(t_end))
    a("inline constexpr double kSodDiaphragm = %s;" % d(x0))
    for key, name in (("rarefaction_head_speed", "RarefactionHead"),
                      ("rarefaction_tail_speed", "RarefactionTail"),
                      ("contact_speed", "Contact"),
                      ("shock_speed", "Shock")):
        a("inline constexpr double kSod%sPosition = %s;" % (name, d(x0 + w[key] * t_end)))
    a("")
    a("// --- normal shock at M1 = 2.0 ----------------------------------------------------------")
    a("inline constexpr double kNormalShockM1 = %s;" % d(ns["M1"]))
    a("inline constexpr double kNormalShockM2 = %s;" % d(ns["M2"]))
    a("inline constexpr double kNormalShockDensityRatio = %s;" % d(ns["rho2_over_rho1"]))
    a("inline constexpr double kNormalShockPressureRatio = %s;" % d(ns["p2_over_p1"]))
    a("inline constexpr double kNormalShockTemperatureRatio = %s;" % d(ns["T2_over_T1"]))
    a("inline constexpr double kNormalShockVelocityRatio = %s;" % d(ns["u2_over_u1"]))
    a("")
    # --- compression and expansion: two SYMMETRIC Riemann problems ------------------------
    #
    # verify_defining_properties() is NOT called for these, and the reason is a real limitation of
    # the frozen verifier worth recording rather than working around silently: it asserts that the
    # contact carries a density jump, which is true of every case P17.7 needed but FALSE for a
    # symmetric problem, where rho*_L == rho*_R exactly and there is no contact at all. The
    # shock-specific Rankine-Hugoniot checks are therefore applied directly below instead.
    from riemann_reference import sound_speed
    from mpmath import fabs as _fabs
    for tag, left, right in (
            ("Compression", (mpf("1.0"), mpf("0.4"), mpf("1.0")),
             (mpf("1.0"), mpf("-0.4"), mpf("1.0"))),
            ("Expansion", (mpf("1.0"), mpf("-0.4"), mpf("1.0")),
             (mpf("1.0"), mpf("0.4"), mpf("1.0")))):
        cw = wave_structure(left, right)
        a("")
        a("// --- symmetric %s wave: u_L = %s, u_R = %s, rho = 1, p = 1 ---"
          % (tag.lower(), nstr(left[1], 4), nstr(right[1], 4)))
        a("// left wave: %s     right wave: %s" % (cw["left_wave"], cw["right_wave"]))
        a("inline constexpr double k%sLeftVelocity = %s;" % (tag, d(left[1])))
        a("inline constexpr double k%sRightVelocity = %s;" % (tag, d(right[1])))
        a("inline constexpr double k%sPStar = %s;" % (tag, d(cw["p_star"])))
        a("inline constexpr double k%sUStar = %s;" % (tag, d(cw["u_star"])))
        a("inline constexpr double k%sRhoStar = %s;" % (tag, d(cw["rho_star_left"])))
        if cw["left_wave"] == "shock":
            a("inline constexpr double k%sLeftWaveSpeed = %s;" % (tag, d(cw["left_shock_speed"])))
            a("inline constexpr double k%sRightWaveSpeed = %s;" % (tag, d(cw["shock_speed"])))
            # Rankine-Hugoniot across the right shock, applied directly
            s_sp = cw["shock_speed"]
            d1, v1, p1 = right
            d2, v2, p2 = cw["rho_star_right"], cw["u_star"], cw["p_star"]
            m1 = d1 * (v1 - s_sp)
            m2 = d2 * (v2 - s_sp)
            assert _fabs(m1 - m2) / _fabs(m1) < mpf(10) ** (-40), "%s: RH mass" % tag
            mo1 = p1 + d1 * (v1 - s_sp) ** 2
            mo2 = p2 + d2 * (v2 - s_sp) ** 2
            assert _fabs(mo1 - mo2) / _fabs(mo1) < mpf(10) ** (-40), "%s: RH momentum" % tag
        else:
            a("inline constexpr double k%sLeftHeadSpeed = %s;"
              % (tag, d(cw["rarefaction_head_speed"])))
            a("inline constexpr double k%sLeftTailSpeed = %s;"
              % (tag, d(cw["rarefaction_tail_speed"])))
            a("inline constexpr double k%sRightTailSpeed = %s;"
              % (tag, d(cw["right_rarefaction_tail_speed"])))
            a("inline constexpr double k%sRightHeadSpeed = %s;"
              % (tag, d(cw["right_rarefaction_head_speed"])))
            # the Riemann invariant must hold through the left fan
            inv_a = left[1] + 2 * sound_speed(left[0], left[2]) / (GAMMA - 1)
            inv_b = cw["u_star"] + 2 * sound_speed(cw["rho_star_left"], cw["p_star"]) / (GAMMA - 1)
            assert _fabs(inv_a - inv_b) / _fabs(inv_a) < mpf(10) ** (-40), "%s: invariant" % tag
        a("// symmetric: rho*_L == rho*_R, so there is NO contact -- asserted, not assumed")
        assert _fabs(cw["rho_star_left"] - cw["rho_star_right"]) < mpf(10) ** (-40)
    a("")
    a("// --- 41 spot points of the exact Sod profile at t = 0.2 --------------------------------")
    a("// The C++ sampler must reproduce every one of these to 1e-12. They are the cross-check that")
    a("// keeps the C++ sampling algebra honest without tabulating 1400 rows.")
    a("struct SodSpotPoint {")
    a("  double x;")
    a("  double density;")
    a("  double velocity;")
    a("  double pressure;")
    a("};")
    a("")
    a("inline constexpr SodSpotPoint kSodSpotPoints[] = {")
    n_spots = 41
    for i in range(n_spots):
        x = mpf(i) / (n_spots - 1)
        xi = (x - x0) / t_end
        rho, u, p = sample(SOD_LEFT, SOD_RIGHT, xi)
        a("    {%s, %s, %s, %s}," % (d(x), d(rho), d(u), d(p)))
    a("};")
    a("inline constexpr int kSodSpotPointCount = %d;" % n_spots)
    a("")
    a("}  // namespace cfd::shock_reference")
    a("")

    text = "\n".join(out)
    if path == "-":
        sys.stdout.write(text)
    else:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote %s  (%d lines)" % (path, len(out)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "-"))
