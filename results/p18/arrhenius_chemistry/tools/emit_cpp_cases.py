#!/usr/bin/env python3
"""P18.5 -- emit the FULL G6 matrix as a C++ initializer, with NO HAND TRANSCRIPTION.

WHY THIS EXISTS. The first version of the G6 matrix test transcribed 9 of the reference's 36
cases by hand -- one composition out of four. G6's `measured` clause says "over a matrix of T, p
and composition spanning the intended range", and a single composition is not a composition
matrix. Transcribing the remaining 27 by hand is exactly the kind of step that introduces a wrong
digit in a number nothing else can check, so the cases are GENERATED instead.

This imports arrhenius_reference.py -- the same mpmath module G6 names -- and prints a C++
aggregate initializer at 17 significant figures, which round-trips a double exactly. It adds no
physics of its own.

ZERO-RATE CASES. The "no-H2" composition has C_H2 = 0, so q = 0 and omega_i = 0 EXACTLY. A
relative error is undefined there, so those rows are flagged `true` in the `exactlyZero` field and
the test asserts exact equality with 0 instead of a relative bound. That is a sharper criterion,
not a weaker one.

    python3 emit_cpp_cases.py        # prints the initializer to stdout
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from mpmath import mp, mpf  # noqa: E402

import arrhenius_reference as ref  # noqa: E402

mp.dps = 60


def lit(x):
    """17 significant figures -- round-trips a double exactly."""
    s = mp.nstr(x, 17, strip_zeros=False)
    # a C++ double literal needs a decimal point or an exponent
    if "e" not in s and "E" not in s and "." not in s:
        s += ".0"
    return s


def main():
    compositions = [
        ("stoich-ish", "0.10", "0.80"),
        ("H2-rich", "0.60", "0.30"),
        ("O2-rich", "0.05", "0.90"),
        ("no-H2", "0", "0.50"),
    ]
    print("  // GENERATED by tools/emit_cpp_cases.py from tools/arrhenius_reference.py")
    print("  // (mpmath, dps=60, printed at 17 significant figures). DO NOT EDIT BY HAND.")
    print("  // 4 compositions x 3 pressures x 3 temperatures = 36 cases.")
    print("  const std::vector<Case> cases{")
    count = 0
    for name, h2, o2 in compositions:
        y = {"H2": mpf(h2), "O2": mpf(o2), "H2O": mpf(1) - mpf(h2) - mpf(o2)}
        assert sum(y.values()) == 1, name
        for p in ["50000", "101325", "1000000"]:
            for t in ["800", "1500", "2200"]:
                pp, tt = mpf(p), mpf(t)
                rho = pp / (ref.mixture_gas_constant(y) * tt)
                q = ref.progress_rate(ref.A, ref.N, ref.EA, tt, y, rho)
                om = ref.species_sources(q)
                zero = "true" if q == 0 else "false"
                print(f"      // {name}  p = {p} Pa  T = {t} K")
                print(f"      {{{lit(y['H2'])}, {lit(y['O2'])}, {lit(pp)}, {lit(tt)},")
                print(f"       {lit(rho)}, {lit(q)},")
                print(f"       {lit(om['H2'])}, {lit(om['O2'])}, {lit(om['H2O'])}, {zero}}},")
                count += 1
    print("  };")
    print(f"  // {count} cases emitted")
    assert count == 36, count


if __name__ == "__main__":
    main()
