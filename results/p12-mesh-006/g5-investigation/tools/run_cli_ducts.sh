#!/usr/bin/env bash
# G5 investigation: run the production CLI on square-duct cases, one process per case, in parallel.
# Usage: run_cli_ducts.sh <tag> "<name>:<n>:<axis>[:key=value...]" ...
# Case directories and full outputs live under $HOME/m6g5/<name> (WSL filesystem, not evidence);
# each run's stdout + timing goes to g5-investigation/logs/cli_<name>.log.
R=/mnt/c/Users/Hasib/Desktop/CFDAPP/CFDApp
I=$R/results/p12-mesh-006/g5-investigation
CLI=$R/build/release/apps/cli/cfdapp
W=$HOME/m6g5
mkdir -p $W
tag=$1; shift
echo "# $tag: $(date -u +%Y-%m-%dT%H:%M:%SZ); cfdapp sha256 $(sha256sum $CLI | cut -c1-64)"
for spec in "$@"; do
  IFS=: read -r name n axis rest <<< "$spec"
  extra=${rest//:/ }
  (
    python3 $I/tools/gen_duct_case.py $W/$name $n $axis $extra
    {
      echo "# G5 investigation CLI run '$name': n=$n axis=$axis overrides='$extra'"
      echo "# start $(date -u +%Y-%m-%dT%H:%M:%SZ); host $(uname -srm); cfdapp sha256 $(sha256sum $CLI | cut -c1-64)"
      echo "# case: $W/$name (generated by tools/gen_duct_case.py from cases/duct_3d)"
      echo
      /usr/bin/time -f "# elapsed %e s, peak RSS %M KB" $CLI --case $W/$name 2>&1
      echo "# exit: $?"
      echo "# fields.csv sha256 $(sha256sum $W/$name/results/fields.csv 2>/dev/null | cut -c1-64)"
      echo "# end $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    } > $I/logs/cli_$name.log 2>&1
    echo "$name done: $(grep -E '^Converged|^Iterations' $I/logs/cli_$name.log | tr '\n' ' ')"
  ) &
done
wait
